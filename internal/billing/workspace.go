// BillingAdjustmentInput changes a charge before it is invoiced.
type BillingAdjustmentInput struct {
	LineID           uuid.UUID `json:"lineId"`
	Kind             string    `json:"kind" enum:"quantity,price,discount,service_charge,tax,revenue_allocation"`
	Quantity         string    `json:"quantity,omitempty" doc:"quantity: the new quantity"`
	UnitPrice        string    `json:"unitPrice,omitempty" doc:"price: the new unit price"`
	Amount           string    `json:"amount,omitempty" doc:"discount: the discount before tax; service_charge / tax: the new amount of the charge"`
	BusinessLine     string    `json:"businessLine,omitempty" doc:"revenue_allocation: the new business line"`
	RevenueComponent string    `json:"revenueComponent,omitempty" doc:"revenue_allocation: the new revenue component"`
	Reason           string    `json:"reason"`
	Reference        string    `json:"reference,omitempty" doc:"Supporting reference (approval memo, complaint, PO …)"`
}

type adjLine struct {
	ID, FolioID, Property         uuid.UUID
	ChargeType, Desc, Line, Comp  string
	Qty, Unit, Net, Svc, Tax, Tot decimal.Decimal
	Liability                     bool
	BenType                       *string
	BenID, Snapshot, Invoice      *uuid.UUID
	Currency, FolioStatus         string
	TaxLines                      []byte
}

// AdjustBilling posts a correcting line for a change of quantity, price,
// discount, service charge, tax or revenue allocation. The original line is
// never changed; the adjustment keeps the previous and the new value.
// Adjustments by an accountant wait for the Finance Manager's approval.
func (s *Service) AdjustBilling(ctx context.Context, tx pgx.Tx, property, folio uuid.UUID, in BillingAdjustmentInput) (BillingRecordDetail, error) {
	if err := handle.Required("reason", in.Reason); err != nil {
		return BillingRecordDetail{}, err
	}
	if _, err := ensureRecord(ctx, tx, property, folio); err != nil {
		return BillingRecordDetail{}, err
	}
	var l adjLine
	var qty, unit, net, svc, tax, tot string
	err := tx.QueryRow(ctx, `SELECT l.id, l.folio_id, l.property_id, l.charge_type, l.description, l.business_line, coalesce(l.revenue_component, l.charge_type),
		l.quantity::text, l.unit_price::text, l.net_amount::text, l.service_amount::text, l.tax_amount::text, l.total::text, l.liability, l.beneficiary_type,
		l.beneficiary_id, l.pricing_snapshot_id, l.invoice_id, f.currency, f.status, l.tax_lines
		FROM billing.folio_lines l JOIN billing.folios f ON f.id = l.folio_id
		WHERE l.id = $1 AND l.folio_id = $2 AND l.voided_at IS NULL FOR UPDATE OF l, f`, in.LineID, folio).
		Scan(&l.ID, &l.FolioID, &l.Property, &l.ChargeType, &l.Desc, &l.Line, &l.Comp, &qty, &unit, &net, &svc, &tax, &tot, &l.Liability, &l.BenType,
			&l.BenID, &l.Snapshot, &l.Invoice, &l.Currency, &l.FolioStatus, &l.TaxLines)
	if dbtx.IsNoRows(err) {
		return BillingRecordDetail{}, errs.Validation("invalid_line", "charge not found on this folio", errs.Field("lineId", "not_found", "not on the folio"))
	}
	if err != nil {
		return BillingRecordDetail{}, err
	}
	if l.Invoice != nil {
		return BillingRecordDetail{}, errs.Conflict("line_invoiced", "the charge is invoiced; issue a credit note on the invoice instead")
	}
	if l.FolioStatus != "open" {
		return BillingRecordDetail{}, ErrFolioClosed // a closed folio is settled; a cancelled one has nothing to bill
	}
	l.Qty, l.Unit, l.Net, l.Svc, l.Tax, l.Tot = dec(qty), dec(unit), dec(net), dec(svc), dec(tax), dec(tot)
	// current values: the line with the adjustments already made to it
	var curNet, curSvc, curTax string
	if err := tx.QueryRow(ctx, `SELECT coalesce(sum(net_amount), 0)::text, coalesce(sum(service_amount), 0)::text, coalesce(sum(tax_amount), 0)::text
		FROM billing.folio_lines WHERE voided_at IS NULL AND (id = $1 OR (reference_type = 'billing.adjustment' AND reference_id = $1))`, l.ID).
		Scan(&curNet, &curSvc, &curTax); err != nil {
		return BillingRecordDetail{}, err
	}
	last := func(kind, def string) (string, error) {
		var v string
		err := tx.QueryRow(ctx, `SELECT new_value FROM billing.billing_adjustments WHERE folio_line_id = $1 AND kind = $2 ORDER BY created_at DESC LIMIT 1`,
			l.ID, kind).Scan(&v)
		if dbtx.IsNoRows(err) {
			return def, nil
		}
		return v, err
	}
	pl := places(l.Currency)
	r := func(d decimal.Decimal) decimal.Decimal { return d.Round(pl) }
	type delta struct {
		net, svc, tax  decimal.Decimal
		line, comp     string
		desc, chargeTy string
	}
	var (
		deltas   []delta
		prev, nv string
	)
	// a change of quantity × unit price splits like the line: on the net
	// amount, or on the all-in total when the unit price includes tax
	part := func(d decimal.Decimal) delta { return delta{net: r(d)} }
	if !l.Net.IsZero() {
		svcRate, taxRate := l.Svc.Div(l.Net), l.Tax.Div(l.Net)
		part = func(d decimal.Decimal) delta { return delta{net: r(d), svc: r(d.Mul(svcRate)), tax: r(d.Mul(taxRate))} }
		if l.Qty.Mul(l.Unit).Sub(l.Net).Abs().GreaterThan(decimal.NewFromInt(1)) && l.Qty.Mul(l.Unit).Sub(l.Tot).Abs().LessThanOrEqual(decimal.NewFromInt(1)) &&
			!l.Tot.IsZero() {
			netShare := l.Net.Div(l.Tot)
			part = func(d decimal.Decimal) delta {
				n := r(d.Mul(netShare))
				return delta{net: n, svc: r(n.Mul(svcRate)), tax: r(d.Sub(n).Sub(r(n.Mul(svcRate))))}
			}
		}
	}
	curQty, curUnit := l.Qty, l.Unit
	if v, err := last("quantity", l.Qty.String()); err != nil {
		return BillingRecordDetail{}, err
	} else {
		curQty = dec(v)
	}
	if v, err := last("price", l.Unit.String()); err != nil {
		return BillingRecordDetail{}, err
	} else {
		curUnit = dec(v)
	}
	label := strings.ReplaceAll(in.Kind, "_", " ")
	switch in.Kind {
	case "quantity", "price":
		if l.ChargeType == "discount" {
			return BillingRecordDetail{}, errs.Conflict("not_adjustable", "a discount line is changed by another discount")
		}
		newQty, newUnit := curQty, curUnit
		if in.Kind == "quantity" {
			q, err := handle.Decimal("quantity", in.Quantity, decimal.Zero)
			if err != nil || !q.IsPositive() {
				return BillingRecordDetail{}, handle.Invalid("quantity", "invalid", "a quantity above zero")
			}
			newQty, prev, nv = q, curQty.String(), q.String()
		} else {
			p, err := handle.Decimal("unitPrice", in.UnitPrice, decimal.NewFromInt(-1))
			if err != nil || p.IsNegative() {
				return BillingRecordDetail{}, handle.Invalid("unitPrice", "invalid", "zero or more")
			}
			newUnit, prev, nv = p, curUnit.String(), p.String()
		}
		if prev == nv {
			return BillingRecordDetail{}, errs.Conflict("no_change", "the value is unchanged")
		}
		d := part(newQty.Mul(newUnit).Sub(curQty.Mul(curUnit)))
		d.desc = fmt.Sprintf("Adjustment %s %s → %s · %s", label, prev, nv, l.Desc)
		deltas = append(deltas, d)
	case "discount":
		a, err := handle.Decimal("amount", in.Amount, decimal.Zero)
		if err != nil || !a.IsPositive() {
			return BillingRecordDetail{}, handle.Invalid("amount", "invalid", "a discount above zero")
		}
		cn := dec(curNet)
		if a.GreaterThan(cn) {
			return BillingRecordDetail{}, handle.Invalid("amount", "too_high", "at most the net amount of the charge ("+cn.StringFixed(pl)+")")
		}
		var given string
		if err := tx.QueryRow(ctx, `SELECT coalesce(sum(-net_amount), 0)::text FROM billing.folio_lines WHERE voided_at IS NULL AND reference_type = 'billing.adjustment'
			AND reference_id = $1 AND charge_type = 'discount'`, l.ID).Scan(&given); err != nil {
			return BillingRecordDetail{}, err
		}
		ratio := a.Div(cn)
		d := delta{net: r(a.Neg()), svc: r(dec(curSvc).Mul(ratio).Neg()), tax: r(dec(curTax).Mul(ratio).Neg()), chargeTy: "discount"}
		prev, nv = dec(given).StringFixed(pl), dec(given).Add(a).StringFixed(pl)
		d.desc = "Discount · " + l.Desc
		deltas = append(deltas, d)
	case "service_charge", "tax":
		a, err := handle.Decimal("amount", in.Amount, decimal.NewFromInt(-1))
		if err != nil || a.IsNegative() {
			return BillingRecordDetail{}, handle.Invalid("amount", "invalid", "zero or more")
		}
		cur := dec(curSvc)
		if in.Kind == "tax" {
			cur = dec(curTax)
		}
		if a.Equal(cur) {
			return BillingRecordDetail{}, errs.Conflict("no_change", "the value is unchanged")
		}
		d := delta{svc: a.Sub(cur)}
		if in.Kind == "tax" {
			d = delta{tax: a.Sub(cur)}
		}
		prev, nv = cur.StringFixed(pl), a.StringFixed(pl)
		d.desc = fmt.Sprintf("Adjustment %s %s → %s · %s", label, prev, nv, l.Desc)
		deltas = append(deltas, d)
	case "revenue_allocation":
		if !slices.Contains(BusinessLines, in.BusinessLine) {
			return BillingRecordDetail{}, handle.Invalid("businessLine", "invalid", "unknown business line")
		}
		if !slices.Contains(RevenueComponents, in.RevenueComponent) && !slices.Contains(chargeTypes, in.RevenueComponent) {
			return BillingRecordDetail{}, handle.Invalid("revenueComponent", "invalid", "unknown revenue component")
		}
		curAlloc, err := last("revenue_allocation", l.Line+"/"+l.Comp)
		if err != nil {
			return BillingRecordDetail{}, err
		}
		nv = in.BusinessLine + "/" + in.RevenueComponent
		if nv == curAlloc {
			return BillingRecordDetail{}, errs.Conflict("no_change", "the allocation is unchanged")
		}
		cl, cc, _ := strings.Cut(curAlloc, "/")
		var an, as, at string
		if err := tx.QueryRow(ctx, `SELECT coalesce(sum(net_amount), 0)::text, coalesce(sum(service_amount), 0)::text, coalesce(sum(tax_amount), 0)::text
			FROM billing.folio_lines WHERE voided_at IS NULL AND (id = $1 OR (reference_type = 'billing.adjustment' AND reference_id = $1))
			AND business_line = $2 AND coalesce(revenue_component, charge_type) = $3`, l.ID, cl, cc).Scan(&an, &as, &at); err != nil {
			return BillingRecordDetail{}, err
		}
		prev = curAlloc
		deltas = append(deltas,
			delta{net: dec(an).Neg(), svc: dec(as).Neg(), tax: dec(at).Neg(), line: cl, comp: cc, desc: "Revenue moved to " + nv + " · " + l.Desc},
			delta{net: dec(an), svc: dec(as), tax: dec(at), line: in.BusinessLine, comp: in.RevenueComponent, desc: "Revenue moved from " + prev + " · " + l.Desc})
	default:
		return BillingRecordDetail{}, handle.Invalid("kind", "invalid", "quantity, price, discount, service_charge, tax or revenue_allocation")
	}
	amount := decimal.Zero
	posted := []uuid.UUID{}
	for _, d := range deltas {
		if d.line == "" {
			d.line, d.comp = l.Line, l.Comp
		}
		if d.chargeTy == "" {
			d.chargeTy = l.ChargeType
			if in.Kind == "revenue_allocation" {
				d.chargeTy = "other"
				if slices.Contains(chargeTypes, d.comp) {
					d.chargeTy = d.comp
				}
			}
		}
		lid, err := postAdjustmentLine(ctx, tx, l, d.chargeTy, d.desc, d.line, d.comp, d.net, d.svc, d.tax)
		if err != nil {
			return BillingRecordDetail{}, err
		}
		posted = append(posted, lid)
		amount = amount.Add(d.net).Add(d.svc).Add(d.tax)
	}
	approved := authz.From(ctx) != nil && authz.From(ctx).Can(PermBillingApprove, &property)
	var approvedAt *time.Time
	if approved {
		now := time.Now().UTC()
		approvedAt = &now
	}
	if _, err := tx.Exec(ctx, `INSERT INTO billing.billing_adjustments (id, property_id, folio_id, folio_line_id, kind, previous_value, new_value, amount,
		posted_line_ids, reason, reference, approved_at, approved_by, created_by) VALUES ($1,$2,$3,$4,$5,$6,$7,$8::numeric,$9,$10,$11,$12,$13,$14)`,
		id.New(), property, folio, l.ID, in.Kind, prev, nv, amount.String(), posted, in.Reason, nullStr(strings.TrimSpace(in.Reference)), approvedAt,
		func() *uuid.UUID {
			if approved {
				return id.Ptr(actor(ctx))
			}
			return nil
		}(), id.Ptr(actor(ctx))); err != nil {
		return BillingRecordDetail{}, err
	}
	kind := map[string]string{"discount": "discount_changed", "tax": "tax_changed"}[in.Kind]
	if kind == "" {
		kind = "billing_adjusted"
	}
	if err := billingEvent(ctx, tx, property, folio, kind, fmt.Sprintf("%s of %s: %s → %s (%s)", strings.ToUpper(label[:1])+label[1:], l.Desc, prev, nv,
		amount.StringFixed(pl)), map[string]any{"lineId": l.ID, "kind": in.Kind, "previous": prev, "new": nv, "amount": amount.String(),
		"reference": in.Reference, "approved": approved}, in.Reason); err != nil {
		return BillingRecordDetail{}, err
	}
	return GetBillingRecord(ctx, tx, property, folio)
}

// postAdjustmentLine posts a correcting line on the (locked, open) folio: it
// references the adjusted line and keeps its pricing snapshot, liability, tax
// lines and beneficiary.
func postAdjustmentLine(ctx context.Context, tx pgx.Tx, src adjLine, chargeType, desc, line, comp string, net, svc, tax decimal.Decimal) (uuid.UUID, error) {
	total := net.Add(svc).Add(tax)
	comps, _ := json.Marshal([]map[string]any{{"code": comp, "name": strings.ReplaceAll(comp, "_", " "), "amount": net.String(), "liability": src.Liability}})
	lid := id.New()
	taxes := src.TaxLines
	if taxes == nil {
		taxes = []byte("[]")
	}
	if _, err := tx.Exec(ctx, `INSERT INTO billing.folio_lines (id, property_id, folio_id, charge_type, description, quantity, unit_price, net_amount,
		tax_amount, service_amount, total, currency, components, pricing_snapshot_id, reference_type, reference_id, liability, posted_by, business_line,
		revenue_component, tax_lines, beneficiary_type, beneficiary_id)
		VALUES ($1,$2,$3,$4,$5,1,$6::numeric,$6::numeric,$7::numeric,$8::numeric,$9::numeric,$10,$11,$12,'billing.adjustment',$13,$14,$15,$16,$17,$18,$19,$20)`,
		lid, src.Property, src.FolioID, chargeType, desc, net.String(), tax.String(), svc.String(), total.String(), src.Currency, comps, src.Snapshot, src.ID,
		src.Liability, id.Ptr(actor(ctx)), line, comp, taxes, src.BenType, src.BenID); err != nil {
		return uuid.Nil, err
	}
	_, err := tx.Exec(ctx, `UPDATE billing.folios SET version = version + 1, updated_by = $2 WHERE id = $1`, src.FolioID, id.Ptr(actor(ctx)))
	return lid, err
}

