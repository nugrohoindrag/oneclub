// GetBillingRecord loads the Review / Prepare Billing view of a folio.
func GetBillingRecord(ctx context.Context, q dbtx.Querier, property, folio uuid.UUID) (BillingRecordDetail, error) {
	it, err := BillingItemOf(ctx, q, property, folio)
	if err != nil {
		return BillingRecordDetail{}, err
	}
	d := BillingRecordDetail{Item: it, Record: BillingRecord{AttachmentFileIDs: []uuid.UUID{}}}
	rec, err := handle.List[BillingRecord](q.Query(ctx, `SELECT r.customer_id, r.corporate_account_id, r.bill_to_name, r.bill_to_address, r.bill_to_npwp, r.bill_to_email,
		r.bill_to_phone, r.terms_days, r.customer_po, r.contract_ref, r.billing_ref, r.notes, r.internal_notes, r.attachment_file_ids, r.ready_at,
		ru.full_name AS ready_by_name, trim_scale(r.approved_amount)::text AS approved_amount, r.approved_at, au.full_name AS approved_by_name, r.version
		FROM billing.billing_records r LEFT JOIN platform.users ru ON ru.id = r.ready_by LEFT JOIN platform.users au ON au.id = r.approved_by
		WHERE r.folio_id = $1`, folio))
	if err != nil {
		return d, err
	}
	if len(rec) == 1 {
		d.Record = rec[0]
		if d.Record.AttachmentFileIDs == nil {
			d.Record.AttachmentFileIDs = []uuid.UUID{}
		}
	}
	if d.Lines, err = handle.List[BillingLine](q.Query(ctx, `SELECT id, charge_type, description, business_line, coalesce(revenue_component, charge_type) AS revenue_component,
		trim_scale(quantity)::text AS quantity, trim_scale(unit_price)::text AS unit_price, trim_scale(net_amount)::text AS net_amount,
		trim_scale(service_amount)::text AS service_amount, trim_scale(tax_amount)::text AS tax_amount, trim_scale(total)::text AS total,
		reference_type, reference_id, invoice_id, posted_at FROM billing.folio_lines WHERE folio_id = $1 AND voided_at IS NULL ORDER BY posted_at, id`, folio)); err != nil {
		return d, err
	}
	gross, disc, svc, tax := decimal.Zero, decimal.Zero, decimal.Zero, decimal.Zero
	for _, l := range d.Lines {
		if l.InvoiceID != nil {
			continue
		}
		net := dec(l.NetAmount)
		if l.ChargeType == "discount" || net.IsNegative() {
			disc = disc.Sub(net)
		} else {
			gross = gross.Add(net)
		}
		svc, tax = svc.Add(dec(l.ServiceAmount)), tax.Add(dec(l.TaxAmount))
	}
	var paid, deposit, transferred string
	if err := q.QueryRow(ctx, `SELECT f.currency,
		coalesce((SELECT sum(amount - refunded_amount) FROM billing.payments p WHERE p.folio_id = f.id AND p.status IN ('completed', 'refunded')
		  AND p.purpose = 'settlement' AND p.method_type NOT IN ('member_account', 'folio_transfer')), 0)::text,
		coalesce((SELECT sum(CASE WHEN d.status = 'held' THEN d.amount ELSE d.applied_amount END) FROM billing.deposits d
		  WHERE d.folio_id = f.id AND d.status IN ('held', 'applied')), 0)::text,
		coalesce((SELECT sum(amount - refunded_amount) FROM billing.payments p WHERE p.folio_id = f.id AND p.status IN ('completed', 'refunded')
		  AND p.purpose = 'settlement' AND p.method_type IN ('member_account', 'folio_transfer')), 0)::text
		FROM billing.folios f WHERE f.id = $1`, folio).Scan(&d.Currency, &paid, &deposit, &transferred); err != nil {
		return d, err
	}
	pl := places(d.Currency)
	d.Breakdown = BillingBreakdown{GrossCharges: gross.StringFixed(pl), Discount: disc.StringFixed(pl), ServiceCharge: svc.StringFixed(pl), Tax: tax.StringFixed(pl),
		Deposit: dec(deposit).StringFixed(pl), Payments: dec(paid).StringFixed(pl), Transferred: dec(transferred).StringFixed(pl),
		ToInvoice: dec(it.ToInvoice).StringFixed(pl)}
	drs, err := q.Query(ctx, `SELECT id, number, folio_id, payment_id, amount::text, applied_amount::text, currency, status, applied_at, created_at
		FROM billing.deposits WHERE folio_id = $1 ORDER BY created_at`, folio)
	if err != nil {
		return d, err
	}
	d.Deposits = []Deposit{}
	for drs.Next() {
		var x Deposit
		if err := drs.Scan(&x.ID, &x.Number, &x.FolioID, &x.PaymentID, &x.Amount, &x.AppliedAmount, &x.Currency, &x.Status, &x.AppliedAt, &x.CreatedAt); err != nil {
			drs.Close()
			return d, err
		}
		d.Deposits = append(d.Deposits, x)
	}
	drs.Close()
	if d.Adjustments, err = handle.List[BillingAdjustment](q.Query(ctx, `SELECT a.id, a.folio_line_id, l.description AS line_label, a.kind, a.previous_value,
		a.new_value, trim_scale(a.amount)::text AS amount, a.reason, a.reference, a.created_at, cu.full_name AS created_by_name, a.approved_at,
		au.full_name AS approved_by_name
		FROM billing.billing_adjustments a JOIN billing.folio_lines l ON l.id = a.folio_line_id
		LEFT JOIN platform.users cu ON cu.id = a.created_by LEFT JOIN platform.users au ON au.id = a.approved_by
		WHERE a.folio_id = $1 ORDER BY a.created_at DESC`, folio)); err != nil {
		return d, err
	}
	if d.History, err = billingHistory(ctx, q, folio); err != nil {
		return d, err
	}
	failed := map[string]string{}
	for _, e := range it.Exceptions {
		if e.Resolved == nil {
			if k, ok := checkOf[e.Code]; ok && failed[k] == "" {
				failed[k] = e.Message
			}
		}
	}
	if it.Blocking > 0 {
		failed["exceptions"] = fmt.Sprintf("%d blocking exception(s)", it.Blocking)
	}
	held := decimal.Zero
	for _, x := range d.Deposits {
		if x.Status == "held" {
			held = held.Add(dec(x.Amount).Sub(dec(x.AppliedAmount)))
		}
	}
	for _, c := range checkMap {
		ch := BillingCheck{Key: c.key, Label: c.label, OK: failed[c.key] == "", Detail: failed[c.key]}
		if c.key == "deposit" && held.IsPositive() {
			ch.Detail = "Held deposits of " + held.StringFixed(pl) + " are applied when the invoice is issued"
		}
		d.Checks = append(d.Checks, ch)
	}
	if bc, err := newBillingContext(ctx, q, property); err == nil {
		d.Approval = bc.approvalLevel(dec(it.ToInvoice))
	} else {
		return d, err
	}
	day, err := CurrentBusinessDate(ctx, q, property)
	if err != nil {
		return d, err
	}
	d.BusinessDay = day.Format("2006-01-02")
	return d, nil
}

// billingHistory is the trail of a folio: charges, deposits and payments,
// the billing work and the invoices with their credit notes.
func billingHistory(ctx context.Context, q dbtx.Querier, folio uuid.UUID) ([]BillingHistoryEntry, error) {
	return handle.List[BillingHistoryEntry](q.Query(ctx, `
		SELECT l.posted_at AS at, 'charge_created' AS kind, l.description AS summary, u.full_name AS actor, trim_scale(l.total)::text AS amount, NULL::uuid AS ref
		  FROM billing.folio_lines l LEFT JOIN platform.users u ON u.id = l.posted_by WHERE l.folio_id = $1
		UNION ALL
		SELECT l.voided_at, 'charge_voided', l.description || coalesce(' · ' || l.void_reason, ''), u.full_name, trim_scale(l.total)::text, NULL
		  FROM billing.folio_lines l LEFT JOIN platform.users u ON u.id = l.voided_by WHERE l.folio_id = $1 AND l.voided_at IS NOT NULL
		UNION ALL
		SELECT d.created_at, 'deposit_received', 'Deposit ' || d.number, NULL, trim_scale(d.amount)::text, NULL FROM billing.deposits d WHERE d.folio_id = $1
		UNION ALL
		SELECT d.applied_at, 'deposit_applied', 'Deposit ' || d.number || ' applied', NULL, trim_scale(d.applied_amount)::text, NULL
		  FROM billing.deposits d WHERE d.folio_id = $1 AND d.applied_at IS NOT NULL
		UNION ALL
		SELECT coalesce(p.paid_at, p.created_at), CASE WHEN p.method_type = 'member_account' THEN 'ar_transfer' ELSE 'payment' END,
		  CASE WHEN p.method_type = 'member_account' THEN 'Moved to the AR account · ' || coalesce(p.reference, p.number)
		    ELSE 'Payment ' || p.number || ' · ' || replace(p.method_type, '_', ' ') || ' · ' || p.status END, NULL,
		  trim_scale(p.amount)::text, NULL FROM billing.payments p WHERE p.folio_id = $1 AND p.purpose = 'settlement'
		UNION ALL
		SELECT e.created_at, e.kind, e.summary, e.actor_name, e.detail->>'total', (e.detail->>'invoiceId')::uuid
		  FROM billing.billing_events e WHERE e.folio_id = $1
		UNION ALL
		SELECT i.created_at, 'invoice_created', 'Invoice ' || coalesce(i.number, 'draft') || ' · ' || i.bill_to_name, u.full_name, trim_scale(i.total)::text, i.id
		  FROM billing.invoices i LEFT JOIN platform.users u ON u.id = i.created_by
		  WHERE (i.folio_id = $1 OR i.id IN (SELECT invoice_id FROM billing.folio_lines WHERE folio_id = $1 AND invoice_id IS NOT NULL))
		  -- generated here: the billing event already tells it
		  AND NOT EXISTS (SELECT 1 FROM billing.billing_events e WHERE e.folio_id = $1 AND e.kind = 'invoice_generated' AND e.detail->>'invoiceId' = i.id::text)
		UNION ALL
		SELECT i.issued_at, 'invoice_posted', 'Invoice ' || i.number || ' issued and posted to AR', NULL, trim_scale(i.total)::text, i.id
		  FROM billing.invoices i WHERE i.issued_at IS NOT NULL
		  AND (i.folio_id = $1 OR i.id IN (SELECT invoice_id FROM billing.folio_lines WHERE folio_id = $1 AND invoice_id IS NOT NULL))
		UNION ALL
		SELECT i.sent_at, 'invoice_sent', 'Invoice ' || i.number || ' sent to ' || coalesce(i.bill_to_email, i.bill_to_name), NULL, NULL, i.id
		  FROM billing.invoices i WHERE i.sent_at IS NOT NULL
		  AND (i.folio_id = $1 OR i.id IN (SELECT invoice_id FROM billing.folio_lines WHERE folio_id = $1 AND invoice_id IS NOT NULL))
		UNION ALL
		SELECT i.voided_at, 'invoice_voided', 'Invoice ' || coalesce(i.number, 'draft') || ' voided' || coalesce(' · ' || i.void_reason, ''), NULL,
		  trim_scale(i.total)::text, i.id FROM billing.invoices i WHERE i.voided_at IS NOT NULL
		  AND (i.folio_id = $1 OR i.id IN (SELECT il.invoice_id FROM billing.invoice_lines il JOIN billing.folio_lines fl ON fl.id = il.folio_line_id WHERE fl.folio_id = $1))
		UNION ALL
		SELECT c.created_at, 'credit_note_created', 'Credit note ' || c.number || ' · ' || c.reason, NULL, trim_scale(c.amount)::text, c.invoice_id
		  FROM billing.credit_notes c WHERE c.invoice_id IN (SELECT invoice_id FROM billing.folio_lines WHERE folio_id = $1 AND invoice_id IS NOT NULL)
		ORDER BY at DESC`, folio))
}

