// Billing workspace (Revenue & Billing → Billing,
// docs/Revenue_Billing_Billing_Workspace_Improvement_Requirements.md): the
// folios with charges still to bill, grouped by the business that created
// them, with the next action of each one.
//
//   - pending billing: charges exist but the folio is still open and nobody
//     marked it ready;
//   - ready to invoice: the folio is closed (or marked ready) and every
//     validation passed;
//   - exception: closed or marked ready, but a blocking exception is open;
//   - invoiced: every charge is on an invoice (Invoices owns it from there);
//   - cancelled: the folio was cancelled after billing work started.
//
// Exceptions are derived from the folio, its charges and the bill-to party,
// never stored, so they clear once the data is fixed. What Finance prepared
// (bill-to, payment term, references, owner, ready, approval, acknowledged
// exceptions) is the billing record of the folio (billing.billing_records).
// Invoices are generated by CreateInvoice / IssueInvoice (number, AR
// transfer, accounting event, customer portal, PDF) and sent with the
// invoice template.

