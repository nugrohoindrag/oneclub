// BillingWorkspacePolicy are the validation and approval thresholds of the
// billing workspace.
type BillingWorkspacePolicy struct {
	ApprovalThreshold          string `json:"approvalThreshold" doc:"Amounts to invoice from this value need the Finance Manager's approval (0 = never)"`
	ExecutiveApprovalThreshold string `json:"executiveApprovalThreshold" doc:"From this value the General Manager / Director approves (0 = never)"`
	DocumentThreshold          string `json:"documentThreshold" doc:"Company billing from this value needs a PO, contract or supporting document (0 = never)"`
	RequireCompanyNPWP         bool   `json:"requireCompanyNpwp" doc:"A company billed with tax needs its NPWP (tax invoice)"`
}

// DefaultBillingWorkspacePolicy: approval from Rp100 jt, executive from
// Rp500 jt, documents for company billing from Rp25 jt.
var DefaultBillingWorkspacePolicy = BillingWorkspacePolicy{ApprovalThreshold: "100000000", ExecutiveApprovalThreshold: "500000000",
	DocumentThreshold: "25000000", RequireCompanyNPWP: true}

func init() {
	rules.RegisterPolicy(rules.PolicyDef{Code: "billing.workspace", Category: "Credit Policies", Name: "Billing validation & approval",
		Description: "Approval thresholds of billing (Finance Manager, General Manager / Director) and when company billing needs NPWP and supporting documents",
		Default:     DefaultBillingWorkspacePolicy})
}

// LoadBillingWorkspacePolicy returns the billing workspace policy in force.
func LoadBillingWorkspacePolicy(ctx context.Context, q dbtx.Querier, property uuid.UUID) (BillingWorkspacePolicy, error) {
	p, _, err := rules.PolicyAt(ctx, q, "billing.workspace", property, DefaultBillingWorkspacePolicy)
	return p, err
}

// billingGroups maps a folio source to its business.
var billingGroups = []struct {
	key, label string
	sources    []string
}{
	{"golf", "Golf", []string{"golf_booking", "tournament", "golf_round", "walk_in", "bag_storage"}},
	{"resort", "Resort", []string{"reservation", "stay", "package_booking"}},
	{"events", "Events & Meetings", []string{"banquet_event", "quotation"}},
	{"membership", "Membership", []string{"membership_fee", "membership_renewal", "membership"}},
	{"sport", "Sport Club", []string{"sport_entry", "class_enrollment", "locker"}},
	{"fnb", "F&B & Retail", []string{"pos_order", "voucher_sale"}},
	{"other", "Other", nil},
}

func billingGroup(source string) string {
	for _, g := range billingGroups {
		if slices.Contains(g.sources, source) {
			return g.key
		}
	}
	return "other"
}

