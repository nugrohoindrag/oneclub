// SaveBillingRecord saves Prepare Billing (FR: Save Billing).
func SaveBillingRecord(ctx context.Context, tx pgx.Tx, property, folio uuid.UUID, in BillingRecordInput) (BillingRecordDetail, error) {
	if in.TermsDays != nil && *in.TermsDays < 0 {
		return BillingRecordDetail{}, handle.Invalid("termsDays", "invalid", "zero or more days")
	}
	if in.CorporateAccountID != nil {
		var ok bool
		if err := tx.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM crm.corporate_accounts WHERE id = $1 AND property_id = $2)`, *in.CorporateAccountID, property).
			Scan(&ok); err != nil || !ok {
			return BillingRecordDetail{}, handle.Invalid("corporateAccountId", "not_found", "not in this property")
		}
	}
	if in.CustomerID != nil {
		var ok bool
		if err := tx.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM crm.customers WHERE id = $1 AND property_id = $2)`, *in.CustomerID, property).
			Scan(&ok); err != nil || !ok {
			return BillingRecordDetail{}, handle.Invalid("customerId", "not_found", "not in this property")
		}
	}
	files, err := invoiceFiles(ctx, tx, in.AttachmentFileIDs)
	if err != nil {
		return BillingRecordDetail{}, err
	}
	number, err := ensureRecord(ctx, tx, property, folio)
	if err != nil {
		return BillingRecordDetail{}, err
	}
	rows, err := tx.Query(ctx, `SELECT customer_id, corporate_account_id, bill_to_name, bill_to_address, bill_to_npwp, bill_to_email,
		bill_to_phone, terms_days, customer_po, contract_ref, billing_ref, notes, internal_notes, attachment_file_ids, version
		FROM billing.billing_records WHERE folio_id = $1`, folio)
	before, err := handle.One[BillingRecord](rows, err, "billing record")
	if err != nil {
		return BillingRecordDetail{}, err
	}
	if _, err := tx.Exec(ctx, `UPDATE billing.billing_records SET customer_id = $2, corporate_account_id = $3, bill_to_name = $4, bill_to_address = $5,
		bill_to_npwp = $6, bill_to_email = $7, bill_to_phone = $8, terms_days = $9, customer_po = $10, contract_ref = $11, billing_ref = $12, notes = $13,
		internal_notes = $14, attachment_file_ids = $15, version = version + 1, updated_by = $16 WHERE folio_id = $1`,
		folio, in.CustomerID, in.CorporateAccountID, nullStr(strings.TrimSpace(in.BillToName)), nullStr(strings.TrimSpace(in.BillToAddress)),
		nullStr(strings.TrimSpace(in.BillToNPWP)), nullStr(strings.TrimSpace(in.BillToEmail)), nullStr(strings.TrimSpace(in.BillToPhone)), in.TermsDays,
		nullStr(strings.TrimSpace(in.CustomerPO)), nullStr(strings.TrimSpace(in.ContractRef)), nullStr(strings.TrimSpace(in.BillingRef)),
		nullStr(strings.TrimSpace(in.Notes)), nullStr(strings.TrimSpace(in.InternalNotes)), files, id.Ptr(actor(ctx))); err != nil {
		return BillingRecordDetail{}, err
	}
	changed := []string{}
	cmp := func(field string, a, b any) {
		ja, _ := json.Marshal(a)
		jb, _ := json.Marshal(b)
		if string(ja) != string(jb) {
			changed = append(changed, field)
		}
	}
	nz := func(s string) *string { return nullStr(strings.TrimSpace(s)) }
	cmp("bill to customer", before.CustomerID, in.CustomerID)
	cmp("bill to company", before.CorporateAccountID, in.CorporateAccountID)
	cmp("bill-to name", before.BillToName, nz(in.BillToName))
	cmp("billing address", before.BillToAddress, nz(in.BillToAddress))
	cmp("NPWP", before.BillToNPWP, nz(in.BillToNPWP))
	cmp("e-mail", before.BillToEmail, nz(in.BillToEmail))
	cmp("payment term", before.TermsDays, in.TermsDays)
	cmp("references", []any{before.CustomerPO, before.ContractRef, before.BillingRef}, []any{nz(in.CustomerPO), nz(in.ContractRef), nz(in.BillingRef)})
	cmp("notes", []any{before.Notes, before.InternalNotes}, []any{nz(in.Notes), nz(in.InternalNotes)})
	cmp("documents", before.AttachmentFileIDs, files)
	if len(changed) > 0 {
		if err := billingEvent(ctx, tx, property, folio, "billing_edited", "Billing edited: "+strings.Join(changed, ", "),
			map[string]any{"folio": number, "changed": changed}, ""); err != nil {
			return BillingRecordDetail{}, err
		}
	}
	return GetBillingRecord(ctx, tx, property, folio)
}

// MarkReady marks a folio ready to invoice once every validation passed.
func MarkReady(ctx context.Context, tx pgx.Tx, property, folio uuid.UUID) (BillingRecordDetail, error) {
	number, err := ensureRecord(ctx, tx, property, folio)
	if err != nil {
		return BillingRecordDetail{}, err
	}
	it, err := BillingItemOf(ctx, tx, property, folio)
	if err != nil {
		return BillingRecordDetail{}, err
	}
	if it.Status == BillInvoiced || it.Status == BillSettled {
		return BillingRecordDetail{}, errs.Conflict("nothing_to_bill", "the folio has nothing left to bill")
	}
	if it.Blocking > 0 {
		return BillingRecordDetail{}, errs.Conflict("billing_exceptions", "resolve the blocking exceptions first: "+exceptionList(it))
	}
	if _, err := tx.Exec(ctx, `UPDATE billing.billing_records SET status = 'ready', ready_at = now(), ready_by = $2, version = version + 1, updated_by = $2
		WHERE folio_id = $1`, folio, id.Ptr(actor(ctx))); err != nil {
		return BillingRecordDetail{}, err
	}
	if err := billingEvent(ctx, tx, property, folio, "billing_marked_ready", "Billing marked ready to invoice",
		map[string]any{"folio": number, "toInvoice": it.ToInvoice}, ""); err != nil {
		return BillingRecordDetail{}, err
	}
	return GetBillingRecord(ctx, tx, property, folio)
}

// errKind is the kind of an application error ("" for any other error).
func errKind(err error) errs.Kind {
	var e *errs.Error
	if errors.As(err, &e) {
		return e.Kind
	}
	return ""
}

func exceptionList(it BillingItem) string {
	var out []string
	for _, e := range it.Exceptions {
		if e.Resolved == nil {
			out = append(out, e.Label)
		}
	}
	return strings.Join(out, ", ")
}

// ApproveBilling approves the amount to invoice and the adjustments of a
// folio (Finance Manager; General Manager / Director from the executive
// threshold).
func ApproveBilling(ctx context.Context, tx pgx.Tx, property, folio uuid.UUID, reason string) (BillingRecordDetail, error) {
	number, err := ensureRecord(ctx, tx, property, folio)
	if err != nil {
		return BillingRecordDetail{}, err
	}
	it, err := BillingItemOf(ctx, tx, property, folio)
	if err != nil {
		return BillingRecordDetail{}, err
	}
	bc, err := newBillingContext(ctx, tx, property)
	if err != nil {
		return BillingRecordDetail{}, err
	}
	if bc.approvalLevel(dec(it.ToInvoice)) == "executive" {
		if err := authz.RequireAt(ctx, PermBillingApproveExecutive, property); err != nil {
			return BillingRecordDetail{}, errs.Forbidden("billing of this value is approved by the General Manager / Director")
		}
	}
	if _, err := tx.Exec(ctx, `UPDATE billing.billing_records SET approved_amount = $2::numeric, approved_at = now(), approved_by = $3, version = version + 1,
		updated_by = $3 WHERE folio_id = $1`, folio, it.ToInvoice, id.Ptr(actor(ctx))); err != nil {
		return BillingRecordDetail{}, err
	}
	tag, err := tx.Exec(ctx, `UPDATE billing.billing_adjustments SET approved_at = now(), approved_by = $2 WHERE folio_id = $1 AND approved_at IS NULL`,
		folio, id.Ptr(actor(ctx)))
	if err != nil {
		return BillingRecordDetail{}, err
	}
	summary := "Billing approved for " + it.ToInvoice
	if n := tag.RowsAffected(); n > 0 {
		summary += fmt.Sprintf(" with %d adjustment(s)", n)
	}
	if err := billingEvent(ctx, tx, property, folio, "billing_approved", summary,
		map[string]any{"folio": number, "amount": it.ToInvoice, "adjustments": tag.RowsAffected()}, reason); err != nil {
		return BillingRecordDetail{}, err
	}
	return GetBillingRecord(ctx, tx, property, folio)
}

// ResolveException acknowledges (accountant) or overrides (Finance Manager)
// an exception with a reason.
func ResolveException(ctx context.Context, tx pgx.Tx, property, folio uuid.UUID, code, reason string) (BillingRecordDetail, error) {
	if err := handle.Required("reason", reason); err != nil {
		return BillingRecordDetail{}, err
	}
	if _, err := ensureRecord(ctx, tx, property, folio); err != nil {
		return BillingRecordDetail{}, err
	}
	it, err := BillingItemOf(ctx, tx, property, folio)
	if err != nil {
		return BillingRecordDetail{}, err
	}
	var ex *BillingException
	for i := range it.Exceptions {
		if it.Exceptions[i].Code == code {
			ex = &it.Exceptions[i]
		}
	}
	if ex == nil {
		return BillingRecordDetail{}, errs.Conflict("exception_not_found", "the folio has no such exception (already fixed?)")
	}
	switch ex.Resolution {
	case "fix":
		return BillingRecordDetail{}, errs.Conflict("fix_required", ex.Message+": correct the data in Prepare Billing")
	case "approve":
		return ApproveBilling(ctx, tx, property, folio, reason)
	case "override":
		if err := authz.RequireAt(ctx, PermBillingApprove, property); err != nil {
			return BillingRecordDetail{}, errs.Forbidden("only the Finance Manager can override " + ex.Label)
		}
	}
	name := ""
	if p := authz.From(ctx); p != nil {
		name = p.Name
	}
	res, _ := json.Marshal(BillingResolution{Reason: reason, By: actor(ctx), ByName: name, At: time.Now().UTC()})
	if _, err := tx.Exec(ctx, `UPDATE billing.billing_records SET resolved = resolved || jsonb_build_object($2::text, $3::jsonb), version = version + 1,
		updated_by = $4 WHERE folio_id = $1`, folio, code, res, id.Ptr(actor(ctx))); err != nil {
		return BillingRecordDetail{}, err
	}
	verb := "acknowledged"
	if ex.Resolution == "override" {
		verb = "overridden"
	}
	if err := billingEvent(ctx, tx, property, folio, "exception_resolved", ex.Label+" "+verb+": "+reason,
		map[string]any{"code": code, "resolution": ex.Resolution}, reason); err != nil {
		return BillingRecordDetail{}, err
	}
	return GetBillingRecord(ctx, tx, property, folio)
}

