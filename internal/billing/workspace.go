// BillingResolution is who acknowledged or overrode an exception.
type BillingResolution struct {
	Reason string    `json:"reason"`
	By     uuid.UUID `json:"by"`
	ByName string    `json:"byName"`
	At     time.Time `json:"at"`
}

// BillingException is one issue that stops (or may stop) invoicing.
type BillingException struct {
	Code     string `json:"code" enum:"missing_customer,missing_billing_entity,missing_billing_address,missing_tax_information,invalid_tax_configuration,pricing_mismatch,unresolved_folio,duplicate_charge,missing_supporting_document,invalid_payment_term,revenue_allocation_error,approval_required"`
	Label    string `json:"label"`
	Severity string `json:"severity" enum:"high,medium"`
	Message  string `json:"message"`
	// Resolution: fix = correct the data (Prepare Billing, adjustment, folio);
	// acknowledge = the accountant accepts it with a reason; override = the
	// Finance Manager overrides it with a reason; approve = the approver approves the billing.
	Resolution string             `json:"resolution" enum:"fix,acknowledge,override,approve"`
	Resolved   *BillingResolution `json:"resolved,omitempty" doc:"Acknowledged or overridden: no longer blocking"`
}

