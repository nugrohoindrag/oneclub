// invoiceInputOf builds the invoice request of a prepared folio.
func invoiceInputOf(ctx context.Context, q dbtx.Querier, folio uuid.UUID) (InvoiceInput, error) {
	in := InvoiceInput{FolioID: &folio, Issue: true}
	recs, err := handle.List[BillingRecord](q.Query(ctx, `SELECT customer_id, corporate_account_id, bill_to_name, bill_to_address, bill_to_npwp, bill_to_email,
		bill_to_phone, terms_days, customer_po, contract_ref, billing_ref, notes, internal_notes, attachment_file_ids FROM billing.billing_records
		WHERE folio_id = $1`, folio))
	if err != nil || len(recs) == 0 {
		return in, err
	}
	r := recs[0]
	in.CustomerID, in.CorporateAccountID, in.TermsDays = r.CustomerID, r.CorporateAccountID, r.TermsDays
	in.BillTo = &BillTo{Name: deref(r.BillToName), Address: deref(r.BillToAddress), NPWP: deref(r.BillToNPWP), Email: deref(r.BillToEmail), Phone: deref(r.BillToPhone)}
	in.CustomerPO, in.ContractRef, in.BillingRef = deref(r.CustomerPO), deref(r.ContractRef), deref(r.BillingRef)
	in.Notes, in.InternalNotes, in.AttachmentFileIDs = deref(r.Notes), deref(r.InternalNotes), r.AttachmentFileIDs
	return in, nil
}

// issueAndSend creates, issues and (optionally) sends one invoice inside a
// savepoint, so one failing folio does not stop the batch.
func (h *HTTP) issueAndSend(ctx context.Context, tx pgx.Tx, property uuid.UUID, in InvoiceInput, send bool, folios []uuid.UUID, summary string) (InvoiceDetail, bool, error) {
	sp, err := tx.Begin(ctx)
	if err != nil {
		return InvoiceDetail{}, false, err
	}
	d, err := h.CreateInvoice(ctx, sp, property, in)
	sent := false
	if err == nil && send {
		if err = h.sendInvoice(ctx, sp, property, d.Invoice, "billing.invoice", nil); err == nil {
			if _, err = sp.Exec(ctx, `UPDATE billing.invoices SET sent_at = now() WHERE id = $1`, d.ID); err == nil {
				sent = true
				err = audit.Record(ctx, sp, audit.Entry{Module: "billing", Action: "send", EntityType: "billing.invoice", EntityID: d.ID.String(),
					EntityLabel: deref(d.Number), PropertyID: &property})
			}
		}
	}
	if err == nil {
		for _, f := range folios {
			if err = billingEvent(ctx, sp, property, f, "invoice_generated", fmt.Sprintf(summary, deref(d.Number)),
				map[string]any{"invoiceId": d.ID, "number": d.Number, "total": d.Total, "sent": sent}, ""); err != nil {
				break
			}
		}
	}
	if err != nil {
		_ = sp.Rollback(ctx)
		return InvoiceDetail{}, false, err
	}
	return d, sent, sp.Commit(ctx)
}

// GenerateInvoices generates one invoice per folio for the folios without a
// blocking exception; the others are skipped with the reason.
func (h *HTTP) GenerateInvoices(ctx context.Context, tx pgx.Tx, property uuid.UUID, in BillingGenerateInput) (BillingGenerateResults, error) {
	if len(in.FolioIDs) == 0 {
		return BillingGenerateResults{}, handle.Invalid("folioIds", "required", "choose the folios to invoice")
	}
	if len(in.FolioIDs) > 200 {
		return BillingGenerateResults{}, handle.Invalid("folioIds", "too_many", "at most 200 folios at once")
	}
	if err := authz.RequireAt(ctx, "billing.invoice.issue", property); err != nil {
		return BillingGenerateResults{}, err
	}
	out := BillingGenerateResults{Results: []BillingGenerateResult{}}
	seen := map[uuid.UUID]bool{}
	for _, fid := range in.FolioIDs {
		if seen[fid] {
			continue
		}
		seen[fid] = true
		it, err := BillingItemOf(ctx, tx, property, fid)
		if err != nil {
			if errKind(err) == errs.KindNotFound {
				out.Results = append(out.Results, BillingGenerateResult{FolioID: fid, Error: "folio not found"})
				out.Skipped++
				if err := audit.Record(ctx, tx, audit.Entry{Module: "billing", Action: "invoice_skipped", EntityType: "billing.billing_record",
					EntityID: fid.String(), PropertyID: &property, Reason: "folio not found"}); err != nil {
					return out, err
				}
				continue
			}
			return out, err
		}
		res := BillingGenerateResult{FolioID: fid, Number: it.Number}
		switch {
		case it.Status == BillInvoiced || it.Status == BillSettled || it.Status == BillCancelled:
			res.Error = "nothing to invoice (" + strings.ReplaceAll(it.Status, "_", " ") + ")"
		case !it.CanInvoice:
			res.Error = "requires attention: " + exceptionList(it)
		}
		if res.Error == "" {
			req, err := invoiceInputOf(ctx, tx, fid)
			if err != nil {
				return out, err
			}
			d, sent, err := h.issueAndSend(ctx, tx, property, req, in.Send, []uuid.UUID{fid}, "Invoice %s generated")
			if err != nil {
				if errKind(err) == "" || errKind(err) == errs.KindInternal {
					return out, err
				}
				res.Error = err.Error()
			} else {
				res.InvoiceID, res.InvoiceNumber, res.Total, res.Sent = &d.ID, d.Number, d.Total, sent
			}
		}
		if res.Error != "" {
			out.Skipped++
			if err := audit.Record(ctx, tx, audit.Entry{Module: "billing", Action: "invoice_skipped", EntityType: "billing.billing_record", EntityID: fid.String(),
				EntityLabel: it.Number, PropertyID: &property, Reason: res.Error}); err != nil {
				return out, err
			}
		} else {
			out.Generated++
		}
		out.Results = append(out.Results, res)
	}
	return out, nil
}

// ConsolidateInput combines folios of one payer into one invoice.
type ConsolidateInput struct {
	FolioIDs  []uuid.UUID `json:"folioIds"`
	TermsDays *int        `json:"termsDays,omitempty" doc:"Default: the first folio's billing, or Credit Policies"`
	Send      bool        `json:"send,omitempty"`
}

// ConsolidateBilling generates one invoice for several folios of the same
// payer, each invoice line linked to its source folio charge (Finance
// Manager approves consolidated billing).
func (h *HTTP) ConsolidateBilling(ctx context.Context, tx pgx.Tx, property uuid.UUID, in ConsolidateInput) (BillingGenerateResult, error) {
	ids := []uuid.UUID{}
	for _, x := range in.FolioIDs {
		if !slices.Contains(ids, x) {
			ids = append(ids, x)
		}
	}
	if len(ids) < 2 {
		return BillingGenerateResult{}, handle.Invalid("folioIds", "too_few", "choose at least two folios")
	}
	if err := authz.RequireAt(ctx, "billing.invoice.issue", property); err != nil {
		return BillingGenerateResult{}, err
	}
	var payer string
	var customer, company *uuid.UUID
	numbers := []string{}
	for _, fid := range ids {
		it, err := BillingItemOf(ctx, tx, property, fid)
		if err != nil {
			return BillingGenerateResult{}, err
		}
		if it.Status == BillInvoiced || it.Status == BillSettled || it.Status == BillCancelled {
			return BillingGenerateResult{}, errs.Conflict("nothing_to_invoice", it.Number+" has nothing to invoice")
		}
		// approval of each folio is replaced by the approval of the consolidation
		blocking := []string{}
		for _, e := range it.Exceptions {
			if e.Resolved == nil && e.Code != "approval_required" {
				blocking = append(blocking, e.Label)
			}
		}
		if len(blocking) > 0 {
			return BillingGenerateResult{}, errs.Conflict("billing_exceptions", it.Number+" requires attention: "+strings.Join(blocking, ", "))
		}
		key := "none"
		switch it.BillToKind {
		case "company":
			key = "company:" + it.CorporateAccountID.String()
		case "customer":
			key = "customer:" + it.CustomerID.String()
		}
		if payer == "" {
			payer, customer, company = key, it.CustomerID, it.CorporateAccountID
		} else if payer != key {
			return BillingGenerateResult{}, errs.Conflict("payer_mismatch", "every folio of a consolidated invoice must be billed to the same company or customer ("+it.Number+" differs)")
		}
		numbers = append(numbers, it.Number)
	}
	req, err := invoiceInputOf(ctx, tx, ids[0])
	if err != nil {
		return BillingGenerateResult{}, err
	}
	req.FolioID, req.FolioIDs, req.CustomerID, req.CorporateAccountID = nil, ids, customer, company
	if in.TermsDays != nil {
		req.TermsDays = in.TermsDays
	}
	if req.BillingRef == "" {
		req.BillingRef = strings.Join(numbers, ", ")
	}
	d, sent, err := h.issueAndSend(ctx, tx, property, req, in.Send, ids, "Consolidated invoice %s generated ("+strings.Join(numbers, ", ")+")")
	if err != nil {
		return BillingGenerateResult{}, err
	}
	return BillingGenerateResult{FolioID: ids[0], Number: strings.Join(numbers, ", "), InvoiceID: &d.ID, InvoiceNumber: d.Number, Total: d.Total, Sent: sent}, nil
}

// BillingSplitInput splits a folio across billing parties.
type BillingSplitInput struct {
	CustomerID         *uuid.UUID `json:"customerId,omitempty"`
	CorporateAccountID *uuid.UUID `json:"corporateAccountId,omitempty"`
	Amount             string     `json:"amount,omitempty" doc:"Amount moved to the other party (or percent)"`
	Percent            string     `json:"percent,omitempty"`
	Reason             string     `json:"reason"`
}

// SplitBilling moves a share of every uninvoiced charge of an open folio to
// another payer; the original folio and its lines are kept (SplitCharges).
func (s *Service) SplitBilling(ctx context.Context, tx pgx.Tx, property, folio uuid.UUID, in BillingSplitInput) (SplitResult, error) {
	if in.CustomerID == nil && in.CorporateAccountID == nil {
		return SplitResult{}, handle.Invalid("corporateAccountId", "required", "choose the company or the customer that pays the share")
	}
	var lines []uuid.UUID
	var total string
	if err := tx.QueryRow(ctx, `SELECT coalesce(array_agg(id ORDER BY posted_at, id), '{}'), coalesce(sum(total), 0)::text FROM billing.folio_lines
		WHERE folio_id = $1 AND property_id = $2 AND voided_at IS NULL AND invoice_id IS NULL`, folio, property).Scan(&lines, &total); err != nil {
		return SplitResult{}, err
	}
	t := dec(total)
	if len(lines) == 0 || !t.IsPositive() {
		return SplitResult{}, errs.Conflict("nothing_to_split", "the folio has no uninvoiced charges")
	}
	pct := strings.TrimSpace(in.Percent)
	if pct == "" {
		a, err := handle.Decimal("amount", in.Amount, decimal.Zero)
		if err != nil || !a.IsPositive() || a.GreaterThan(t) {
			return SplitResult{}, handle.Invalid("amount", "invalid", "between 0 and "+t.String())
		}
		pct = a.Div(t).Mul(decimal.NewFromInt(100)).Round(6).String()
	}
	res, err := s.SplitCharges(ctx, tx, property, SplitInput{LineIDs: lines, Percent: pct, CustomerID: in.CustomerID, CorporateAccountID: in.CorporateAccountID,
		Reason: in.Reason})
	if err != nil {
		return res, err
	}
	summary := fmt.Sprintf("Billing split: %s (%s%%) moved to %s, folio %s", res.Moved, pct, res.TargetFolio.HolderName, res.TargetFolio.Number)
	if err := billingEvent(ctx, tx, property, folio, "billing_split", summary, map[string]any{"targetFolio": res.TargetFolio.ID, "moved": res.Moved,
		"percent": pct}, in.Reason); err != nil {
		return res, err
	}
	return res, billingEvent(ctx, tx, property, res.TargetFolio.ID, "billing_split", "Split from the original folio: "+res.Moved,
		map[string]any{"sourceFolio": folio, "moved": res.Moved, "percent": pct}, in.Reason)
}

// AssignInput assigns an owner to folios.
type AssignInput struct {
	FolioIDs []uuid.UUID `json:"folioIds"`
	OwnerID  *uuid.UUID  `json:"ownerId,omitempty" doc:"null: unassign"`
}

// AssignOwner sets the person responsible for the billing of folios.
func AssignOwner(ctx context.Context, tx pgx.Tx, property uuid.UUID, in AssignInput) (int, error) {
	if len(in.FolioIDs) == 0 {
		return 0, handle.Invalid("folioIds", "required", "choose the folios")
	}
	name := "nobody"
	if in.OwnerID != nil {
		if err := tx.QueryRow(ctx, `SELECT full_name FROM platform.users WHERE id = $1 AND status = 'active'`, *in.OwnerID).Scan(&name); err != nil {
			if dbtx.IsNoRows(err) {
				return 0, handle.Invalid("ownerId", "not_found", "unknown or inactive user")
			}
			return 0, err
		}
	}
	n := 0
	for _, fid := range in.FolioIDs {
		if _, err := ensureRecord(ctx, tx, property, fid); err != nil {
			return n, err
		}
		if _, err := tx.Exec(ctx, `UPDATE billing.billing_records SET owner_id = $2, version = version + 1, updated_by = $3 WHERE folio_id = $1`,
			fid, in.OwnerID, id.Ptr(actor(ctx))); err != nil {
			return n, err
		}
		if err := billingEvent(ctx, tx, property, fid, "owner_assigned", "Owner: "+name, map[string]any{"ownerId": in.OwnerID}, ""); err != nil {
			return n, err
		}
		n++
	}
	return n, nil
}

