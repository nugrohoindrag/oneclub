// billingEvent records a step of the billing work (history and audit).
func billingEvent(ctx context.Context, tx pgx.Tx, property, folio uuid.UUID, kind, summary string, detail map[string]any, reason string) error {
	if detail == nil {
		detail = map[string]any{}
	}
	raw, _ := json.Marshal(detail)
	name := ""
	if p := authz.From(ctx); p != nil {
		name = p.Name
	}
	if _, err := tx.Exec(ctx, `INSERT INTO billing.billing_events (id, property_id, folio_id, kind, summary, detail, actor_id, actor_name)
		VALUES ($1,$2,$3,$4,$5,$6,$7,$8)`, id.New(), property, folio, kind, summary, raw, id.Ptr(actor(ctx)), nullStr(name)); err != nil {
		return err
	}
	return audit.Record(ctx, tx, audit.Entry{Module: "billing", Action: kind, EntityType: "billing.billing_record", EntityID: folio.String(),
		EntityLabel: summary, PropertyID: &property, After: detail, Reason: reason})
}

// ensureRecord opens the billing record of a folio of the property (locked).
func ensureRecord(ctx context.Context, tx pgx.Tx, property, folio uuid.UUID) (string, error) {
	var number, status string
	if err := tx.QueryRow(ctx, `SELECT number, status FROM billing.folios WHERE id = $1 AND property_id = $2`, folio, property).Scan(&number, &status); err != nil {
		if dbtx.IsNoRows(err) {
			return "", errs.NotFound("folio")
		}
		return "", err
	}
	if status == "cancelled" {
		return "", errs.Conflict("folio_cancelled", "the folio is cancelled")
	}
	tag, err := tx.Exec(ctx, `INSERT INTO billing.billing_records (id, property_id, folio_id, created_by, updated_by) VALUES ($1,$2,$3,$4,$4)
		ON CONFLICT (folio_id) DO NOTHING`, id.New(), property, folio, id.Ptr(actor(ctx)))
	if err != nil {
		return "", err
	}
	if tag.RowsAffected() == 1 {
		if err := billingEvent(ctx, tx, property, folio, "billing_opened", "Billing opened for folio "+number, nil, ""); err != nil {
			return "", err
		}
	}
	if _, err := tx.Exec(ctx, `SELECT 1 FROM billing.billing_records WHERE folio_id = $1 FOR UPDATE`, folio); err != nil {
		return "", err
	}
	return number, nil
}

