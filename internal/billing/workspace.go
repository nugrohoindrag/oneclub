// billingRows loads the folios of the workspace (one folio when folio is set,
// whatever its state).
func billingRows(ctx context.Context, q dbtx.Querier, property uuid.UUID, folio *uuid.UUID) ([]billingRow, error) {
	components := append(append([]string{}, RevenueComponents...), chargeTypes...)
	return handle.List[billingRow](q.Query(ctx, `WITH b AS MATERIALIZED ( -- computed once (the balance is filtered, shown and sorted)
		  SELECT f.id, f.number, f.holder_name, f.source_type, f.source_id, f.source_ref, f.status, f.created_at, f.closed_at, f.corporate_name,
		    f.customer_id AS folio_customer, f.corporate_account_id AS folio_corporate,
		    coalesce(l.charges, 0) AS charges, coalesce(l.uninvoiced, 0) AS uninvoiced, coalesce(l.uninvoiced_lines, 0) AS uninvoiced_lines,
		    coalesce(l.uninvoiced_tax, 0) AS uninvoiced_tax, coalesce(l.bad_tax, 0) AS bad_tax, coalesce(l.bad_price, 0) AS bad_price,
		    coalesce(l.bad_alloc, 0) AS bad_alloc,
		    -- the same source posted twice (golf player, room night …) and not reversed
		    (SELECT count(*) FROM (SELECT 1 FROM billing.folio_lines x WHERE x.folio_id = f.id AND x.voided_at IS NULL AND x.invoice_id IS NULL
		      AND x.reference_id IS NOT NULL AND coalesce(x.reference_type, '') NOT LIKE 'billing.%'
		      GROUP BY x.reference_type, x.reference_id, x.charge_type HAVING count(*) FILTER (WHERE x.total > 0) > 1 AND sum(x.total) > max(x.total)) g) AS duplicates,
		    coalesce((SELECT sum(amount - refunded_amount) FROM billing.payments p WHERE p.folio_id = f.id AND p.status IN ('completed', 'refunded')
		      AND p.purpose = 'settlement' AND p.method_type NOT IN ('member_account', 'folio_transfer')), 0) AS paid,
		    coalesce((SELECT sum(CASE WHEN d.status = 'held' THEN d.amount ELSE d.applied_amount END) FROM billing.deposits d
		      WHERE d.folio_id = f.id AND d.status IN ('held', 'applied')), 0) AS deposit,
		    -- moved to an AR account (invoice issue, charge to account) or another folio: billed, not paid
		    coalesce((SELECT sum(amount - refunded_amount) FROM billing.payments p WHERE p.folio_id = f.id AND p.status IN ('completed', 'refunded')
		      AND p.purpose = 'settlement' AND p.method_type IN ('member_account', 'folio_transfer')), 0) AS transferred,
		    (SELECT count(*) FROM billing.payments p WHERE p.folio_id = f.id AND p.status = 'pending')
		      + (SELECT count(*) FROM billing.refunds x WHERE x.folio_id = f.id AND x.status = 'pending') AS pending_money,
		    (SELECT count(*) FROM billing.billing_adjustments a WHERE a.folio_id = f.id AND a.approved_at IS NULL) AS unapproved,
		    i.id AS invoice_id, i.number AS invoice_number, i.status AS invoice_status, coalesce(i.paid_amount, 0) AS invoice_paid,
		    CASE WHEN i.status = 'draft' THEN 0 ELSE i.total - i.paid_amount - i.credited_amount - i.written_off_amount END AS outstanding
		  FROM billing.folios f
		  LEFT JOIN LATERAL (SELECT sum(x.total) AS charges, sum(x.total) FILTER (WHERE x.invoice_id IS NULL) AS uninvoiced,
		      count(*) FILTER (WHERE x.invoice_id IS NULL) AS uninvoiced_lines, sum(x.tax_amount) FILTER (WHERE x.invoice_id IS NULL) AS uninvoiced_tax,
		      count(*) FILTER (WHERE x.invoice_id IS NULL AND (abs(x.net_amount + x.tax_amount + x.service_amount - x.total) > 1
		        OR (x.net_amount > 0 AND (x.tax_amount < 0 OR x.service_amount < 0)))) AS bad_tax,
		      -- quantity × unit price matches neither the net nor the all-in amount
		      count(*) FILTER (WHERE x.invoice_id IS NULL AND x.charge_type <> 'discount' AND coalesce(x.reference_type, '') NOT LIKE 'billing.%'
		        AND abs(x.quantity * x.unit_price - x.net_amount) > 1 AND abs(x.quantity * x.unit_price - x.total) > 1) AS bad_price,
		      count(*) FILTER (WHERE x.invoice_id IS NULL AND (x.business_line <> ALL($3::text[])
		        OR coalesce(x.revenue_component, x.charge_type) <> ALL($4::text[]))) AS bad_alloc
		    FROM billing.folio_lines x WHERE x.folio_id = f.id AND x.voided_at IS NULL) l ON true
		  LEFT JOIN LATERAL (SELECT id, number, status, total, paid_amount, credited_amount, written_off_amount FROM billing.invoices v
		    WHERE v.status <> 'void' AND (v.folio_id = f.id OR v.id IN (SELECT y.invoice_id FROM billing.folio_lines y WHERE y.folio_id = f.id AND y.invoice_id IS NOT NULL))
		    ORDER BY v.created_at DESC LIMIT 1) i ON true
		  WHERE f.property_id = $1 AND f.source_type <> 'manual_invoice' AND ($2::uuid IS NULL OR f.id = $2)
		    AND (f.status IN ('open', 'closed') OR $2::uuid IS NOT NULL OR EXISTS (SELECT 1 FROM billing.billing_records r WHERE r.folio_id = f.id)))
		SELECT b.id AS folio_id, b.number, b.holder_name, b.source_type, b.source_id, b.source_ref, b.status AS folio_status, b.created_at, b.closed_at,
		  b.corporate_name, coalesce(r.customer_id, b.folio_customer) AS customer_id, cu.name AS customer_name,
		  coalesce(r.corporate_account_id, b.folio_corporate) AS corporate_account_id, c.name AS company_name, c.status AS company_status,
		  c.archived_at IS NOT NULL AS company_archived, nullif(r.bill_to_name, '') AS bill_to_name,
		  coalesce(nullif(r.bill_to_address, ''), CASE WHEN c.id IS NOT NULL THEN c.address ELSE cu.address END) AS bill_to_address,
		  coalesce(nullif(r.bill_to_npwp, ''), c.npwp) AS bill_to_npwp,
		  r.id IS NOT NULL AS has_record, r.status AS record_status, r.terms_days, r.owner_id, u.full_name AS owner_name, r.ready_at,
		  trim_scale(r.approved_amount)::text AS approved_amount, r.approved_at, coalesce(r.resolved, '{}'::jsonb) AS resolved,
		  (coalesce(r.customer_po, '') <> '' OR coalesce(r.contract_ref, '') <> '' OR coalesce(cardinality(r.attachment_file_ids), 0) > 0) AS has_document,
		  trim_scale(b.charges)::text AS charges, trim_scale(b.uninvoiced)::text AS uninvoiced, b.uninvoiced_lines::int AS uninvoiced_lines,
		  trim_scale(b.uninvoiced_tax)::text AS uninvoiced_tax, b.bad_tax::int AS bad_tax, b.bad_price::int AS bad_price, b.bad_alloc::int AS bad_alloc,
		  b.duplicates::int AS duplicates, trim_scale(b.paid + b.invoice_paid)::text AS paid, trim_scale(b.deposit)::text AS deposit,
		  trim_scale(greatest(b.charges - b.paid - b.deposit - b.transferred, 0))::text AS to_invoice, b.pending_money::int AS pending_money,
		  b.unapproved::int AS unapproved, b.invoice_id, b.invoice_number, b.invoice_status, trim_scale(b.outstanding)::text AS outstanding
		FROM b
		LEFT JOIN billing.billing_records r ON r.folio_id = b.id
		LEFT JOIN crm.corporate_accounts c ON c.id = coalesce(r.corporate_account_id, b.folio_corporate)
		LEFT JOIN crm.customers cu ON cu.id = coalesce(r.customer_id, b.folio_customer)
		LEFT JOIN platform.users u ON u.id = r.owner_id
		WHERE $2::uuid IS NOT NULL OR b.charges - b.paid - b.deposit - b.transferred > 0 OR b.invoice_id IS NOT NULL OR r.id IS NOT NULL
		ORDER BY greatest(b.charges - b.paid - b.deposit - b.transferred, 0) DESC, b.created_at DESC`, property, folio, BusinessLines, components))
}

// billingContext caches what the exceptions of many folios share.
type billingContext struct {
	policy  BillingWorkspacePolicy
	credit  CreditPolicy
	balance map[uuid.UUID]*Account // city ledger per company
}

func newBillingContext(ctx context.Context, q dbtx.Querier, property uuid.UUID) (*billingContext, error) {
	pol, err := LoadBillingWorkspacePolicy(ctx, q, property)
	if err != nil {
		return nil, err
	}
	cp, _, err := LoadCreditPolicy(ctx, q, property)
	if err != nil {
		return nil, err
	}
	return &billingContext{policy: pol, credit: cp, balance: map[uuid.UUID]*Account{}}, nil
}

// companyAccount is the city ledger of a company (a not yet opened one is
// empty and active).
func (bc *billingContext) companyAccount(ctx context.Context, q dbtx.Querier, property, company uuid.UUID) (Account, error) {
	if a, ok := bc.balance[company]; ok {
		return *a, nil
	}
	a := Account{AccountType: "corporate", Status: "active", Balance: "0"}
	var aid uuid.UUID
	err := q.QueryRow(ctx, `SELECT id FROM billing.customer_accounts WHERE property_id = $1 AND corporate_account_id = $2 AND account_type = 'corporate'`,
		property, company).Scan(&aid)
	switch {
	case err == nil:
		if a, err = GetAccount(ctx, q, aid); err != nil {
			return a, err
		}
	case !dbtx.IsNoRows(err):
		return a, err
	}
	bc.balance[company] = &a
	return a, nil
}

// evaluate turns a folio row into a workspace item with its exceptions and
// status.
func (bc *billingContext) evaluate(ctx context.Context, q dbtx.Querier, property uuid.UUID, r billingRow) (BillingItem, error) {
	it := BillingItem{FolioID: r.FolioID, Number: r.Number, HolderName: r.HolderName, SourceType: r.SourceType, SourceID: r.SourceID, SourceRef: r.SourceRef,
		Group: billingGroup(r.SourceType), FolioStatus: r.FolioStatus, CustomerID: r.CustomerID, CustomerName: r.CustomerName, CorporateAccountID: r.CorporateID,
		Charges: r.Charges, Paid: r.Paid, Deposit: r.Deposit, ToInvoice: r.ToInvoice, InvoiceID: r.InvoiceID, InvoiceNumber: r.InvoiceNumber,
		InvoiceStatus: r.InvoiceStatus, Outstanding: r.Outstanding, OwnerID: r.OwnerID, OwnerName: r.OwnerName, Prepared: r.HasRecord,
		MarkedReady: r.RecordStatus != nil && *r.RecordStatus == "ready", ApprovedAt: r.ApprovedAt, CreatedAt: r.CreatedAt, Exceptions: []BillingException{}}
	switch {
	case r.CorporateID != nil && r.CompanyName != nil:
		it.BillTo, it.BillToKind = *r.CompanyName, "company"
	case r.CustomerID != nil && r.CustomerName != nil:
		it.BillTo, it.BillToKind = *r.CustomerName, "customer"
	default:
		it.BillToKind = "none"
	}
	if r.BillToName != nil && it.BillToKind != "none" {
		it.BillTo = *r.BillToName
	}
	it.TermsDays = 0
	if r.CorporateID != nil {
		it.TermsDays = bc.credit.PaymentTermDays
	}
	if r.TermsDays != nil {
		it.TermsDays = *r.TermsDays
	}
	it.DueSince = r.CreatedAt
	if r.ClosedAt != nil {
		it.DueSince = *r.ClosedAt
	}
	if r.ReadyAt != nil && (r.ClosedAt == nil || r.ReadyAt.Before(*r.ClosedAt)) {
		it.DueSince = *r.ReadyAt
	}
	toInvoice := dec(r.ToInvoice)
	billable := toInvoice.IsPositive() && r.UninvoicedLines > 0
	switch {
	case r.FolioStatus == "cancelled" || (r.RecordStatus != nil && *r.RecordStatus == "cancelled"):
		it.Status = BillCancelled
		return it, nil
	case !billable && r.InvoiceID != nil:
		it.Status = BillInvoiced
		return it, nil
	case !billable:
		it.Status = BillSettled
		return it, nil
	}
	resolved := map[string]BillingResolution{}
	_ = json.Unmarshal(r.Resolved, &resolved)
	add := func(code, severity, resolution, msg string) {
		e := BillingException{Code: code, Label: billingExceptionLabels[code], Severity: severity, Resolution: resolution, Message: msg}
		if x, ok := resolved[code]; ok && resolution != "fix" && resolution != "approve" {
			e.Resolved = &x
		}
		it.Exceptions = append(it.Exceptions, e)
	}
	company := r.CorporateID != nil
	if r.CustomerID == nil && !company {
		add("missing_customer", "high", "fix", "Nobody to bill: link a customer or a company to the billing")
	}
	switch {
	case company && (r.CompanyArchived || (r.CompanyStatus != nil && *r.CompanyStatus != "active")):
		add("missing_billing_entity", "high", "fix", fmt.Sprintf("Company %s is inactive: bill another company or the guest", deref(r.CompanyName)))
	case !company && r.CorporateName != nil && strings.TrimSpace(*r.CorporateName) != "":
		add("missing_billing_entity", "high", "override", fmt.Sprintf("The folio names company %q, which is not linked to a corporate account", *r.CorporateName))
	}
	if company && strings.TrimSpace(deref(r.BillToAddress)) == "" {
		add("missing_billing_address", "high", "fix", "The company has no billing address")
	}
	if company && bc.policy.RequireCompanyNPWP && dec(r.UninvoicedTax).IsPositive() && strings.TrimSpace(deref(r.BillToNPWP)) == "" {
		add("missing_tax_information", "high", "override", "The company has no NPWP for the tax invoice (e-Faktur)")
	}
	if r.BadTax > 0 {
		add("invalid_tax_configuration", "high", "fix", fmt.Sprintf("%d charge(s) where net + service + tax does not equal the total", r.BadTax))
	}
	if r.BadPrice > 0 {
		add("pricing_mismatch", "medium", "acknowledge", fmt.Sprintf("%d charge(s) where quantity × unit price does not match the amount", r.BadPrice))
	}
	if r.PendingMoney > 0 {
		add("unresolved_folio", "high", "override", fmt.Sprintf("%d payment(s) or refund(s) on the folio are still pending", r.PendingMoney))
	}
	if r.Duplicates > 0 {
		add("duplicate_charge", "medium", "acknowledge", fmt.Sprintf("%d source transaction(s) charged more than once", r.Duplicates))
	}
	if company && !r.HasDocument {
		if t := dec(bc.policy.DocumentThreshold); t.IsPositive() && toInvoice.GreaterThanOrEqual(t) {
			add("missing_supporting_document", "medium", "acknowledge", "Company billing of this value needs a customer PO, contract or supporting document")
		}
	}
	if company {
		a, err := bc.companyAccount(ctx, q, property, *r.CorporateID)
		if err != nil {
			return it, err
		}
		if err := CheckCredit(ctx, q, property, a, toInvoice); err != nil {
			var e *errs.Error
			if !errors.As(err, &e) || e.Kind != errs.KindConflict {
				return it, err
			}
			add("invalid_payment_term", "high", "fix", "Credit term not available: "+e.Message+"; request a credit override in Corporate Billing")
		}
	} else if it.TermsDays > 0 {
		add("invalid_payment_term", "medium", "acknowledge", fmt.Sprintf("A %d-day credit term for an individual; individuals normally pay at once", it.TermsDays))
	}
	if r.BadAlloc > 0 {
		add("revenue_allocation_error", "high", "fix", fmt.Sprintf("%d charge(s) without a valid business line or revenue component", r.BadAlloc))
	}
	if level := bc.approvalLevel(toInvoice); level != "" || r.Unapproved > 0 {
		approved := r.ApprovedAmount != nil && dec(*r.ApprovedAmount).Equal(toInvoice) && r.Unapproved == 0
		if !approved {
			msg := "Adjustments wait for the Finance Manager's approval"
			if level != "" {
				who := "the Finance Manager"
				if level == "executive" {
					who = "the General Manager / Director"
				}
				msg = fmt.Sprintf("High-value billing (%s) needs the approval of %s", toInvoice.StringFixed(0), who)
			}
			add("approval_required", "high", "approve", msg)
		}
	}
	for _, e := range it.Exceptions {
		if e.Resolved == nil {
			it.Blocking++
		}
	}
	it.CanInvoice = it.Blocking == 0
	due := r.FolioStatus == "closed" || it.MarkedReady
	switch {
	case !due:
		it.Status = BillPending
	case it.Blocking > 0:
		it.Status = BillException
	default:
		it.Status = BillReady
	}
	return it, nil
}

// approvalLevel is "", "manager" or "executive" for an amount to invoice.
func (bc *billingContext) approvalLevel(amount decimal.Decimal) string {
	if t := dec(bc.policy.ExecutiveApprovalThreshold); t.IsPositive() && amount.GreaterThanOrEqual(t) {
		return "executive"
	}
	if t := dec(bc.policy.ApprovalThreshold); t.IsPositive() && amount.GreaterThanOrEqual(t) {
		return "manager"
	}
	return ""
}

// BillingItems evaluates the workspace folios (one folio when folio is set).
func BillingItems(ctx context.Context, q dbtx.Querier, property uuid.UUID, folio *uuid.UUID) ([]BillingItem, error) {
	rows, err := billingRows(ctx, q, property, folio)
	if err != nil {
		return nil, err
	}
	bc, err := newBillingContext(ctx, q, property)
	if err != nil {
		return nil, err
	}
	out := make([]BillingItem, 0, len(rows))
	for _, r := range rows {
		it, err := bc.evaluate(ctx, q, property, r)
		if err != nil {
			return nil, err
		}
		if folio == nil && it.Status == BillSettled {
			continue
		}
		out = append(out, it)
	}
	return out, nil
}

// BillingItemOf evaluates one folio.
func BillingItemOf(ctx context.Context, q dbtx.Querier, property, folio uuid.UUID) (BillingItem, error) {
	items, err := BillingItems(ctx, q, property, &folio)
	if err != nil {
		return BillingItem{}, err
	}
	if len(items) == 0 {
		return BillingItem{}, errs.NotFound("folio")
	}
	return items[0], nil
}

// Queue lists the billing workspace with the per-business summary.
func Queue(ctx context.Context, q dbtx.Querier, property uuid.UUID, status, group, owner, search string, offset, size int) (BillingQueue, error) {
	items, err := BillingItems(ctx, q, property, nil)
	if err != nil {
		return BillingQueue{}, err
	}
	out := BillingQueue{Groups: []BillingGroupSummary{}, Items: []BillingItem{}, Counts: map[string]int{}}
	sums := map[string]*BillingGroupSummary{}
	amounts := map[string][2]decimal.Decimal{}
	for _, g := range billingGroups {
		sums[g.key] = &BillingGroupSummary{Key: g.key, Label: g.label}
	}
	search = strings.ToLower(strings.TrimSpace(search))
	for _, it := range items {
		g, a := sums[it.Group], amounts[it.Group]
		v := dec(it.ToInvoice)
		switch it.Status {
		case BillPending:
			g.Pending++
			a[0] = a[0].Add(v)
		case BillReady:
			g.Ready++
			a[0], a[1] = a[0].Add(v), a[1].Add(v)
		case BillException:
			g.Exceptions++
			a[0] = a[0].Add(v)
		case BillInvoiced:
			g.Invoiced++
		}
		amounts[it.Group] = a
		if group != "" && group != it.Group {
			continue
		}
		if owner != "" && (it.OwnerID == nil || it.OwnerID.String() != owner) {
			continue
		}
		if search != "" && !strings.Contains(strings.ToLower(it.Number+" "+it.HolderName+" "+it.BillTo+" "+deref(it.SourceRef)+" "+deref(it.InvoiceNumber)), search) {
			continue
		}
		out.Counts[it.Status]++
		if status != "" && status != it.Status {
			continue
		}
		if out.Total >= offset && len(out.Items) < size {
			out.Items = append(out.Items, it)
		}
		out.Total++
	}
	for _, g := range billingGroups {
		s, a := sums[g.key], amounts[g.key]
		if s.Pending+s.Ready+s.Exceptions+s.Invoiced == 0 {
			continue
		}
		s.TotalBillable, s.ReadyAmount = a[0].String(), a[1].String()
		out.Groups = append(out.Groups, *s)
	}
	if offset+size < out.Total {
		out.NextCursor = httpx.EncodeCursor("o:" + strconv.Itoa(offset+size))
	}
	return out, nil
}

